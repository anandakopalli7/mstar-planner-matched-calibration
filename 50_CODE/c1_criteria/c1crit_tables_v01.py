#!/usr/bin/env python3
"""c1crit_tables_v01 (5 Nov 2026): renders the companion tables of the note from c1crit_summary_v01.json (no computation beyond
formatting). Output: 60_RESULTS/c1_criteria_sensitivity_v01/C1_CRITERIA_SENSITIVITY_TABLES_v01.md.
Usage: python -B c1crit_tables_v01.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import c1crit_common_v01 as C  # noqa: E402

S = json.load(open(os.path.join(C.OUT, "c1crit_summary_v01.json")))
L = []


def f(x, d=3):
    if x is None:
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int,)):
        return str(x)
    return ("%." + str(d) + "f") % x


def ci(v, d=3):
    return "n/a" if not v else "[%s, %s]" % (f(v[0], d), f(v[1], d))


def h(t):
    L.append("")
    L.append(t)
    L.append("")


L.append("# C1 criteria sensitivity: companion tables (v01, 5 Nov 2026)")
L.append("")
L.append("Generated by `50_CODE/c1_criteria/c1crit_tables_v01.py` from `c1crit_summary_v01.json`. nuScenes development data only "
         "(K8 Linux replicate, 840 scenes, 68 logs, decision mode). Every number is development evidence, not a confirmation.")

# ---------------- Q1
h("## T1. Intra-scene correlation rho of the exceedance indicator (pooled over a population's evaluable cells with exceedances)")
L.append("| Tracker | Arm | Pop | Cells | ANOVA ICC [95 %] | ANOVA upper 80 % | Beta-binomial ML [95 %] | Moment (scene-unweighted) | Implied by log-bootstrap SE: median [IQR] | Per-cell BB p75 | Var obs / model at rho 0.5 (median) |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|")
bb = S.get("lead_item1_bbcheck") or {}
mom = S["Q1_rho_moment"]["by_tracker_arm_pop"]
for key, v in sorted(S["Q1_rho"]["by_tracker_arm_pop"].items()):
    t, a, p = key.split("|")
    if a not in ("Mstar", "B4", "B6", "B0", "B3"):
        continue
    b = (bb.get(t) or {}).get("%s|%s" % (a, p), {})
    m = mom.get(key, {})
    L.append("| %s | %s | %s | %d | %s %s | %s | %s %s | %s | %s %s | %s | %s |" % (
        t.upper(), a, p, v["cells_used"], f(v["anova_pooled"]), ci(v["anova_pooled_ci95"]), f(b.get("anova_pooled_upper80")),
        f(v["bb_pooled"]), ci(v["bb_pooled_ci95"]), f(m.get("moment_pooled")), f(v["implied_cell_median"]), ci(v["implied_cell_iqr"]),
        f(b.get("bb_cell_p75")), f(b.get("fit_var_ratio_obs_over_rho05_median"), 2)))
h("### T1b. Per-cell rho by the cell's exceedance level (all arms, populations and trackers; cells with exceedances, evaluable)")
L.append("| Cell exceedance E | Cells | ANOVA median | BB median (q90) | Moment median (q75, q90) | Implied median (q90) |")
L.append("|---|---|---|---|---|---|")
for band, v in S["Q1_rho"]["bands"].items():
    m = S["Q1_rho_moment"]["bands"].get(band, {})
    L.append("| %s | %d | %s | %s (%s) | %s (%s, %s) | %s (%s) |" % (band, v["cells"], f(v["anova_median"]), f(v["bb_median"]), f(v["bb_q90"]),
                                                         f(m.get("median")), f(m.get("q75")), f(m.get("q90")), f(v["implied_median"]), f(v["implied_q90"])))
h("### T1c. Beta-binomial fit check (per-cell ML fit; medians over cells of observed / model)")
L.append("| Tracker | Arm | Pop | Variance obs / BB fit | Zero-exceedance scenes obs / BB fit | Variance obs / model at rho 0.5 | Zero scenes obs / model at 0.5 |")
L.append("|---|---|---|---|---|---|---|")
for t, d in sorted(bb.items()):
    for k, v in d.items():
        a, p = k.split("|")
        L.append("| %s | %s | %s | %s | %s | %s | %s |" % (t.upper(), a, p, f(v["fit_var_ratio_obs_over_bb_median"], 2), f(v["fit_zero_ratio_obs_over_bb_median"], 2),
                                                     f(v["fit_var_ratio_obs_over_rho05_median"], 2), f(v["fit_zero_ratio_obs_over_rho05_median"], 2)))

# ---------------- Q2
q2 = S["Q2_mc"]
h("## T2. Monte Carlo error of the power rule and of the sup-t flags")
L.append("MC SE of a power estimate at 0.80 with 200 datasets: %s; 2 MC SE band [%s, %s]." % (f(q2["mc_se_at_0.80_200"], 4), f(q2["band_2se"][0]), f(q2["band_2se"][1])))
L.append("")
L.append("| Tracker | Evaluable cells (all arms, pops) within 2 MC SE of 0.80 at 200 | of which M* | Cells changing status, 200 -> 1000 / 2000 datasets | Family-size changes 200 -> 2000 | Verdicts at 200 / 1000 / 2000 | Power seed sets: family-size ranges that vary; verdict changes | Bootstrap seed sets: all-evaluable flag changes (5 sets); verdict changes |")
L.append("|---|---|---|---|---|---|---|---|")
for t, d in q2["trackers"].items():
    fs = "; ".join("%s %s" % (k, "/".join(str(x) for x in v.values())) for k, v in d["family_sizes"].items() if len(set(v.values())) > 1)
    vv = " / ".join("%s" % ("same" if (v["valid_Mstar"], v["formA"], v["formB_v07d"], v["formC"]) == (True, True, True, True) else "CHANGED")
                    for k, v in d["verdicts"].items())
    psr = "; ".join("%s %d-%d" % (k, a, b) for k, (a, b) in d.get("power_seed_family_range", {}).items() if a != b)
    bsf = sum(it["full"]["n_cell_flag_changes"] for it in d.get("boot_seed_sets", {}).values())
    bsv = [s for s, it in d.get("boot_seed_sets", {}).items() if it["full"]["verdict_changed"] or it["fixed_fams"]["verdict_changed"]]
    L.append("| %s | %d | %d | %s | %s | %s | %s; %s | %d; %s |" % (t.upper(), d["n_near_080_at_200"], d["n_near_080_at_200_Mstar"],
                                                       " / ".join(str(d["n_status_changes"].get(k, 0)) for k in ("P1000", "P2000")), fs or "none", vv,
                                                       psr or "none", d.get("power_seed_verdict_changes"), bsf, bsv or "none"))
h("### T2b. Sup-t quantile q (all-evaluable family) and its Monte Carlo error (B = 2000)")
L.append("| Tracker | Arm | Pop | q (K8 seeds) | SD over 6 seed sets | MC SE (resampling the max-t draws) |")
L.append("|---|---|---|---|---|---|")
for t, d in q2["trackers"].items():
    for k, v in d.get("q_spread", {}).items():
        a, p = k.split("|")
        if a in ("Mstar", "B0", "B3", "B4", "B6"):
            L.append("| %s | %s | %s | %s | %s | %s |" % (t.upper(), a, p, f(v["q_base"]), f(v["sd_over_seed_sets"]), f(v["q_mc_se_resampling"])))

# ---------------- Q3
q3 = S["Q3_coverage"]
h("## T3. Coverage of one-sided 95 % unit-bootstrap bounds of one cell, by units per cell (large development cells, truth known)")
L.append("Cells: %s per tracker (both trackers pooled below). 'Near delta' = truth in [0.02, 0.10)." % q3.get("n_cells_per_n"))
L.append("")
L.append("| Units n | Lower, percentile: all / near delta / p10 | Lower, coded: all / near delta | Upper, percentile: all / near delta / p10 | Upper, coded: all / near delta | Zero-SE share |")
L.append("|---|---|---|---|---|---|")
for n, d in q3["by_n"].items():
    L.append("| %s | %s / %s / %s | %s / %s | %s / %s / %s | %s / %s | %s |" % (
        n, f(d["lb_pct"]["mean"]), f(d["lb_pct"].get("mean_truth_0.02_0.10_near_delta")), f(d["lb_pct"]["p10"]),
        f(d["lb_coded"]["mean"]), f(d["lb_coded"].get("mean_truth_0.02_0.10_near_delta")),
        f(d["ub_pct"]["mean"]), f(d["ub_pct"].get("mean_truth_0.02_0.10_near_delta")), f(d["ub_pct"]["p10"]),
        f(d["ub_coded"]["mean"]), f(d["ub_coded"].get("mean_truth_0.02_0.10_near_delta")), f(d["zero_se_mean"])))
q3b = S.get("Q3b_coverage_pooled_and_simultaneous") or {}
if q3b:
    h("### T3b. Pooled cells (HK1c and the pooled flag) and single cells at the Sidak level of 32 cells")
    L.append("| Part | Tracker | n | Level | Lower pct / coded | Upper pct / coded | Upper coded, near delta (min) |")
    L.append("|---|---|---|---|---|---|---|")
    for k, d in sorted(q3b.items(), key=lambda x: (x[0].split("|")[0], x[0].split("|")[1], int(x[0].split("|n")[1]))):
        part, t, n = k.split("|")
        L.append("| %s | %s | %s | %s | %s / %s | %s / %s | %s (%s) |" % (part, t.upper(), n[1:], f(d["level"], 4), f(d["lb_pct"]["mean"]), f(d["lb_coded"]["mean"]),
                                                             f(d["ub_pct"]["mean"]), f(d["ub_coded"]["mean"]),
                                                             f(d["ub_coded"].get("mean_truth_0.02_0.10_near_delta")), f(d["ub_coded"].get("min_truth_0.02_0.10_near_delta"))))

# ---------------- item 5
s5 = S.get("lead_item5_size") or {}
if s5.get("by_variant"):
    h("## T4. Actual one-sided size of the flag at a true delta, by units per cell (Bradley's band [0.025, 0.075])")
    L.append("| Planting | G | Single cell (K = 1) | Family K = 8 | K = 16 | K = 32 | Per-cell flag rate at K = 32 |")
    L.append("|---|---|---|---|---|---|---|")
    for var, d in s5["by_variant"].items():
        for G, r in sorted(d.items(), key=lambda x: int(x[0])):
            fw = r["familywise"]
            L.append("| %s | %s | %s | %s | %s | %s | %s |" % (var, G, f(fw.get("1"), 4), f(fw.get("8"), 4), f(fw.get("16"), 4), f(fw.get("32"), 4),
                                                         f(r["per_cell"].get("32"), 4)))
    L.append("")
    L.append("Smallest G inside the band: %s" % s5.get("smallest_G_in_bradley_band"))

# ---------------- Q4
q4 = S["Q4_sweep"]
h("## T5. Verdict stability (Valid(M*), V_t, Forms A, B, C) under one-at-a-time changes and the (rho, P, F_MIN) grid")
for t, d in q4["trackers"].items():
    b = d["baseline"]
    L.append("**%s baseline** (rho 0.5, P 0.15, F_MIN 6, HK1c 0.03, c 0.03): Valid(M*) %s; not shown above delta: %s; Form A %s, Form B %s, Form C %s (UB %s); M*'s families PD7 %s, SD1_7 %s, PD %s." % (
        t.upper(), f(b["valid_Mstar"]), ", ".join(b["not_shown_v07d"]), f(b["formA"]), f(b["formB_v07d"]), f(b["formC"]), f(b["formC_ub"]),
        b["family_sizes_Mstar"]["PD7"], b["family_sizes_Mstar"]["SD1_7"], b["family_sizes_Mstar"]["PD"]))
    L.append("")
    L.append("| Setting | Valid(M*) | Not shown above delta | Form A | Form B | Form C | M* families PD7 / SD1_7 / PD | M* fails |")
    L.append("|---|---|---|---|---|---|---|---|")
    for k, v in d["oat"].items():
        fails = "; ".join("%s: %s" % (p, ",".join(x)) for p, x in v["Mstar_failing"].items() if x) or "-"
        L.append("| %s | %s | %s | %s | %s | %s | %s / %s / %s | %s |" % (k, f(v["valid_Mstar"]), ", ".join(v["not_shown_v07d"]), f(v["formA"]),
                                                               f(v["formB_v07d"]), f(v["formC"]), v["family_sizes_Mstar"]["PD7"],
                                                               v["family_sizes_Mstar"]["SD1_7"], v["family_sizes_Mstar"]["PD"], fails))
    L.append("")
    L.append("Grid cells that flip the verdict (%s): %s" % (t.upper(), ", ".join(d["grid_flips"]) or "none"))
    L.append("")
    L.append("Comparator rule v07d (flags only) against v07c (flags or HK1c), all settings: %s." % ("identical V_t and Form B" if not d["rule_v07d_vs_v07c_differences"] else d["rule_v07d_vs_v07c_differences"]))
    L.append("")
    L.append("Grid (rho x P), SD1_7 family of M* (floor 6):")
    L.append("")
    rhos = sorted({float(k.split("|")[0].split("=")[1]) for k in d["grid"]})
    ps = sorted({float(k.split("|")[1].split("=")[1]) for k in d["grid"]})
    L.append("| rho \\ P | " + " | ".join(f(p) for p in ps) + " |")
    L.append("|---" * (len(ps) + 1) + "|")
    for r in rhos:
        row = []
        for p in ps:
            g = d["grid"].get("rho=%.4f|P=%.3f|F_MIN=6" % (r, p))
            row.append("n/a" if g is None else "%d%s" % (g["Mstar_family_sizes"]["SD1_7"], "" if g["valid_Mstar"] else " (fails)"))
        L.append("| %s | %s |" % (f(r, 2), " | ".join(row)))
    L.append("")
h3 = S.get("Q4_h3_choice49c") or {}
if h3:
    L.append("H3 comparator set (D16 Choice 49c) on the development joint loss: " + "; ".join(
        "%s: V^J old %s, new %s, HK1c-only comparators %s" % (t.upper(), v["VJ_old_validJ"], v["VJ_new_49c"], v["hk1c_only_comparators"] or "none")
        for t, v in h3["trackers"].items()))

# ---------------- items 3, 4
p34 = S.get("lead_items3_4_power") or {}
if p34:
    h("## T6. M*'s power-qualified family under the power-rule settings (items 3 and 4)")
    L.append("Self-check of the target-only planting code (every base cell at P, against power_family): %s" % p34.get("check"))
    L.append("")
    L.append("Weights (2000 datasets, rho 0.5, P 0.15, all cells): " + "; ".join("%s: family %d, record share %s%s" % (
        k, v["family_size"], f(v["record_share"]), "" if v.get("equals_mc_P2000") in (None,) else (", equals c1crit_mc P2000: " + f(v["equals_mc_P2000"])))
        for k, v in sorted(p34.get("weights", {}).items())))
    L.append("")
    L.append("| Tracker | Pop | Planting | rho | P | Family | Record share | Floor 6 | Moving-car cells in family |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for k, v in sorted(p34.get("grid", {}).items()):
        t, p, pl, rho, P, reps, w = k.split("|")
        L.append("| %s | %s | %s | %s | %s | %d | %s | %s | %d of %d |" % (t.upper(), p, pl, rho[3:], P[1:], v["family_size"], f(v["record_share"]),
                                                                f(v["floor_6_met"]) if v["floor_6_met"] is not None else "-",
                                                                len(v["moving_car_cells_in_family"]), 6))
    L.append("")
    L.append("Item 4: share of the population's M* records covered by the k most powerful cells (rule settings, 2000 datasets):")
    L.append("")
    L.append("| Tracker | Pop | k=5 | 6 | 8 | 10 | 12 | 15 | 20 | Actual family (size, share) | Moving-car share of records | Moving-car cells in family |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for k, v in sorted(p34.get("coverage_topk", {}).items()):
        t, p = k.split("|")
        kk = v["k_most_powerful"]
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %d, %s | %s | %d |" % (t.upper(), p, *[f(kk.get(str(i), kk.get(i))) for i in (5, 6, 8, 10, 12, 15, 20)],
                                                                         v["actual_family_size"], f(v["actual_family_share"]), f(v["moving_car_record_share"]),
                                                                         len(v["moving_car_in_family"])))

# ---------------- item 6
r6 = S.get("lead_item6_removal") or {}
if r6:
    h("## T7. P(a comparator truly at delta in every cell is removed from V_t) (item 6)")
    L.append("| Tracker | Arm | rho | P(removed), rule (each of 9 conditions at 0.95) | P(removed), familywise (each at 1 - 0.05/9) | PD7 cell / family / pooled | SD1_7 | PD |")
    L.append("|---|---|---|---|---|---|---|---|")
    for k, v in sorted(r6.items()):
        t, a, rho = k.split("|")
        bc = v["by_condition_rule"]
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (t.upper(), a, rho[3:], f(v["P_removed_rule"]), f(v["P_removed_familywise9"]),
                                                       " / ".join(f(x) for x in bc["PD7"]), " / ".join(f(x) for x in bc["SD1_7"]), " / ".join(f(x) for x in bc["PD"])))

# ---------------- item 7
o7 = S.get("lead_item7_oc375") or {}
if o7:
    h("## T8. Operating characteristics at 375 units built from development scenes (item 7)")
    L.append("| Variant | P(H1) | P(H1 fails) | P(H1) without floors | T1: P(Form B), M* fail reasons, family median PD7/SD1_7, p10 SD1_7 | T3: same |")
    L.append("|---|---|---|---|---|---|")
    for k, v in o7.items():
        cells = []
        for t in C.TAGS:
            tt = v["trackers"][t]
            fr = ", ".join("%s %s" % (a, f(b)) for a, b in tt["P_Mstar_failure_reason"].items() if b)
            cells.append("%s; %s; %s/%s; %s" % (f(tt["P_formB"]), fr or "none", f(tt["Mstar_family_size_median"]["PD7_primary"], 0),
                                                f(tt["Mstar_family_size_median"]["SD1_7_gap_le_5m"], 0), f(tt["Mstar_family_size_p10"]["SD1_7_gap_le_5m"], 0)))
        L.append("| %s | %s | %s | %s | %s | %s |" % (k, f(v["P_H1"]), f(v["P_H1_fails"]), f(v["P_H1_without_floors"]), cells[0], cells[1]))

# ---------------- Q5
q5 = S["Q5_effect"]
h("## T9. Exceedance of the comparator cells flagged on development (the planted effect's anchor)")
L.append("| Tracker | Arm | Pop | Evaluable | Flagged | Flagged E: median [IQR] (min-max) | Cells with E > delta: median E |")
L.append("|---|---|---|---|---|---|---|")
for t, d in q5["trackers"].items():
    for k, v in d.items():
        a, p = k.split("|")
        if a == "Mstar" or not v["flagged"]:
            continue
        L.append("| %s | %s | %s | %d | %d | %s %s (%s-%s) | %s |" % (t.upper(), a, p, v["evaluable"], v["flagged"], f(v["E_flagged_median"]), ci(v["E_flagged_quartiles"]),
                                                                 f(v["E_flagged_min"]), f(v["E_flagged_max"]), f(v["E_above_delta_median"])))
for g in ("B4_B6", "all_shown_above"):
    v = q5[g]
    L.append("")
    L.append("%s: %d flagged cells, median %s, quantiles 10/25/75/90 %s; PD7 only: %d cells, median %s." % (
        g, v["flagged_cells"], f(v["E_flagged_median"]), [round(x, 3) for x in v["E_flagged_quartiles"]], v["PD7_only_flagged_cells"],
        f(v["PD7_only_E_flagged_median"])))

out = os.path.join(C.OUT, "C1_CRITERIA_SENSITIVITY_TABLES_v01.md")
with open(out, "w", encoding="utf-8") as fh:
    fh.write("\n".join(L) + "\n")
print("TABLES WRITTEN", out)
