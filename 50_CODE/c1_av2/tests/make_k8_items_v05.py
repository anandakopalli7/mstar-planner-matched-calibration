#!/usr/bin/env python3
"""Generator of 50_CODE/k8/k8_items_v05.py from k8_items_v04.py (not modified), asserted replacements (D16 v13 Choice 34.2, 34.6;
R17b A3, M-b). v05 adds:
  * every cache manifest's dataset tag must agree with its scene names (c1_guard_v02.manifest_dataset); --dev and --exploratory
    accept nuScenes caches only; --av2 (stage A, counts only) accepts AV2 stage-A caches only (as v04);
  * --av2-stageB: the confirmatory items, every scene of AV2 stage-B caches, with the error fields; it needs --plan, the frozen C1 plan
    (40_PROTOCOL/C1_PLAN_HASH_LOG.txt only), this file as the plan's entry:k8_items, every loaded module bound, and every cache chained
    to the plan (stage B under this plan from a bound stage-A manifest, c1_guard_v02.chain_cache);
  * the summary records the plan hash, the chains, the dataset and the code record (c1_fit_v03 checks the chain).
Usage (from 50_CODE/c1_av2): python -B tests/make_k8_items_v05.py
"""
import hashlib
import os

C1 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K8 = os.path.join(os.path.dirname(C1), "k8")


def rep(s, old, new):
    assert s.count(old) == 1, "expected one occurrence of %r" % old[:90]
    return s.replace(old, new)


def make(src):
    crlf = "\r\n" in src
    s = src.replace("\r\n", "\n")     # k8_items_v04.py has CRLF line ends: matched as LF, written back as CRLF
    s = rep(s, '"""K8 calibration items, v04 (Claude line',
            '"""K8 calibration items, v05 (Claude line, 4 Nov 2026; generated by 50_CODE/c1_av2/tests/make_k8_items_v05.py from k8_items_v04.py,\n'
            'which is unchanged) = k8_items_v04 plus D16 v13 Choice 34: dataset tags must agree with scene names; --dev and --exploratory take\n'
            'nuScenes caches only; --av2-stageB builds the confirmatory items on AV2 stage-B caches under the frozen C1 plan (entry:k8_items,\n'
            'canonical hash log, every cache chained to a bound stage-A manifest); the summary records the plan hash and the chains.\n'
            'Usage (C1): python -B k8_items_v05.py --caches <stage-B dirs> --out <npz> --av2-stageB --plan <frozen C1 plan> [--workers n]\n'
            'K8 calibration items, v04 (Claude line')
    s = rep(s, 'import k6_sim_v02 as S  # noqa: E402\n',
            'import k6_sim_v02 as S  # noqa: E402\n'
            'sys.path.insert(0, os.path.join(W_ROOT, "50_CODE", "c1_av2"))\n'
            'import c1_guard_v02 as G  # noqa: E402\n')
    s = rep(s, 'DEV_STAMP = "DEV MODE', 'AV2_STAGE_B_STAMP = "C1 AV2 STAGE B items (confirmatory, frozen C1 plan)"\nDEV_STAMP = "DEV MODE')
    s = rep(s, '    ap.add_argument("--counts-only", action="store_true", help="v04: error fields NaN, no ground-truth position read")\n',
            '    ap.add_argument("--counts-only", action="store_true", help="v04: error fields NaN, no ground-truth position read")\n'
            '    ap.add_argument("--av2-stageB", action="store_true", help="v05: every scene of AV2 stage-B caches under the frozen C1 plan")\n'
            '    ap.add_argument("--plan", default=None, help="v05: the frozen C1 plan (required by --av2-stageB)")\n')
    s = rep(s, '    assert int(a.dev) + int(a.exploratory) + int(a.av2) == 1, "exactly one of --dev, --exploratory, --av2"\n',
            '    assert int(a.dev) + int(a.exploratory) + int(a.av2) + int(a.av2_stageB) == 1, "exactly one of --dev, --exploratory, --av2, --av2-stageB"\n'
            '    assert not (a.av2_stageB and a.counts_only), "--av2-stageB builds the confirmatory items (with the error fields)"\n'
            '    plan_sha, frozen, rt, chains = None, None, None, []\n'
            '    if a.av2_stageB:\n'
            '        plan_sha, frozen, rt = G.guard("av2", a.plan, "entry:k8_items", os.path.abspath(__file__))\n'
            '    else:\n'
            '        assert a.plan is None, "--plan goes with --av2-stageB"\n')
    s = rep(s, '        if a.av2:\n            assert man.get("stage") == "A" and man.get("dataset") == "av2", "--av2 needs AV2 stage-A caches: " + mp\n',
            '        ds_ = G.manifest_dataset(man)\n'
            '        if a.av2:\n            assert man.get("stage") == "A" and man.get("dataset") == "av2", "--av2 needs AV2 stage-A caches: " + mp\n'
            '        elif a.av2_stageB:\n'
            '            assert ds_ == "av2", "--av2-stageB needs AV2 caches: " + mp\n'
            '            chains.append(G.chain_cache(mp, plan_sha, frozen))\n'
            '        else:\n'
            '            assert ds_ == "nuscenes", "--dev and --exploratory take nuScenes caches only: " + mp\n')
    s = rep(s, '    elif a.av2:\n        stamp = AV2_STAGE_A_STAMP\n',
            '    elif a.av2:\n        stamp = AV2_STAGE_A_STAMP\n    elif a.av2_stageB:\n        stamp = AV2_STAGE_B_STAMP\n')
    s = rep(s, '            "launch_record": os.path.abspath(lr), "out_sha256": sha256_path(a.out), "seconds": round(time.time() - t0, 1)}\n',
            '            "launch_record": os.path.abspath(lr), "out_sha256": sha256_path(a.out), "seconds": round(time.time() - t0, 1),\n'
            '            "plan_sha256": plan_sha, "chains": chains, "dataset": "av2" if (a.av2 or a.av2_stageB) else "nuscenes",\n'
            '            "code": G.verify_runtime_again(frozen, rt) if rt else G.code_record(os.path.abspath(__file__))}\n')
    s = rep(s, '    print("K8 ITEMS V04 DONE")\n', '    print("K8 ITEMS V05 DONE")\n')
    return s.replace("\n", "\r\n") if crlf else s


def main():
    with open(os.path.join(K8, "k8_items_v04.py"), encoding="utf-8", newline="") as f:
        out = make(f.read())
    with open(os.path.join(K8, "k8_items_v05.py"), "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print(hashlib.sha256(out.encode("utf-8")).hexdigest(), "k8_items_v05.py")


if __name__ == "__main__":
    main()
