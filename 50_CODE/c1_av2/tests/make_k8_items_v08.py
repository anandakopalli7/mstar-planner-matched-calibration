#!/usr/bin/env python3
"""Generator of 50_CODE/k8/k8_items_v08.py from k8_items_v07.py (not modified), asserted replacements (D16 v23 Choice 44f m1, m2, m7).
v08 = v07 on c1_guard_v05: on AV2 (--av2-stageB) the guard writes the chained run-log "start" line before any cache is read, the
deposit record must not name the OSF project and the plan's log line must carry a parsable time, and stale c1_gt_* folders are swept; the
"done" line is chained to it. Line ends are kept as in the source (CRLF).
Usage (from 50_CODE/c1_av2): python -B tests/make_k8_items_v08.py
"""
import hashlib
import os

C1 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K8 = os.path.join(os.path.dirname(C1), "k8")


def rep(s, old, new):
    assert s.count(old) == 1, "expected one occurrence of %r" % old[:90]
    return s.replace(old, new)


def make(src):
    crlf = "\r\n" in src
    s = src.replace("\r\n", "\n")
    s = rep(s, '"""K8 calibration items, v07 (Claude line',
            '"""K8 calibration items, v08 (Claude line, 5 Nov 2026; generated by 50_CODE/c1_av2/tests/make_k8_items_v08.py from k8_items_v07.py,\n'
            'which is unchanged) = k8_items_v07 on c1_guard_v05 (D16 v23 Choice 44f): on AV2 the chained run-log "start" line before any cache\n'
            'is read and the "done" line after (m1); the m2 deposit checks; stale c1_gt_* folders swept (m7).\n'
            'K8 calibration items, v07 (Claude line')
    s = rep(s, "import c1_guard_v04 as G  # noqa: E402\n", "import c1_guard_v05 as G  # noqa: E402\n")
    s = rep(s, '    print("K8 ITEMS V07 DONE")\n', '    print("K8 ITEMS V08 DONE")\n')
    return s.replace("\n", "\r\n") if crlf else s


def main():
    with open(os.path.join(K8, "k8_items_v07.py"), encoding="utf-8", newline="") as f:
        out = make(f.read())
    dst = os.path.join(K8, "k8_items_v08.py")
    if os.path.exists(dst):
        assert open(dst, encoding="utf-8", newline="").read() == out, "k8_items_v08.py exists and differs from the generator's output"
    else:
        with open(dst, "w", encoding="utf-8", newline="") as f:
            f.write(out)
    print(hashlib.sha256(out.encode("utf-8")).hexdigest(), "k8_items_v08.py")


if __name__ == "__main__":
    main()
