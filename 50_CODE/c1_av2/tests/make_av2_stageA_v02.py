#!/usr/bin/env python3
"""Generator of 50_CODE/av2/av2_cache_stageA_v02.py from av2_cache_stageA_v01.py (not modified), asserted replacements (D16 v21 Choice 42f
m3; R17d §3i): future stage-A builds record the scene-to-log map's hash among their inputs ("scene_json", "scene_json_sha256", from
--meta/scene.json when given), so scene.json becomes a recorded stage-A input. Nothing else changes.
Usage (from 50_CODE/c1_av2): python -B tests/make_av2_stageA_v02.py
"""
import hashlib
import os

C1 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AV2 = os.path.join(os.path.dirname(C1), "av2")


def rep(s, old, new):
    assert s.count(old) == 1, "expected one occurrence of %r" % old[:90]
    return s.replace(old, new)


def make(src):
    crlf = "\r\n" in src
    s = src.replace("\r\n", "\n")
    s = rep(s, '              "builder_sha256": sha256_path(os.path.abspath(__file__))}\n',
            '              "builder_sha256": sha256_path(os.path.abspath(__file__))}\n'
            '    if a.meta:   # v02 (D16 v21 Choice 42f m3): the scene-to-log map is a recorded stage-A input\n'
            '        inputs["scene_json"] = os.path.abspath(os.path.join(a.meta, "scene.json"))\n'
            '        inputs["scene_json_sha256"] = sha256_path(os.path.join(a.meta, "scene.json"))\n')
    out = "#!/usr/bin/env python3\n# av2_cache_stageA_v02 (generated by c1_av2/tests/make_av2_stageA_v02.py from av2_cache_stageA_v01, unchanged otherwise):\n" \
          "# records scene.json's hash among the stage-A inputs (D16 v21 Choice 42f m3).\n" + s.split("\n", 1)[1] if s.startswith("#!") else s
    return out.replace("\n", "\r\n") if crlf else out


def main():
    with open(os.path.join(AV2, "av2_cache_stageA_v01.py"), encoding="utf-8", newline="") as f:
        out = make(f.read())
    with open(os.path.join(AV2, "av2_cache_stageA_v02.py"), "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print(hashlib.sha256(out.encode("utf-8")).hexdigest(), "av2_cache_stageA_v02.py")


if __name__ == "__main__":
    main()
