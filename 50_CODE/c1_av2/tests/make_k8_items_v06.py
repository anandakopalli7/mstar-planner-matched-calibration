#!/usr/bin/env python3
"""Generator of 50_CODE/k8/k8_items_v06.py from k8_items_v05.py (not modified), asserted replacements (R17c M1, m5; D16 v18 Choice
39c): v06 is v05 on c1_guard_v03 (the latest line of the C1 hash log only, FROZEN_ENV versions asserted, the log hash recorded in the
items' summary); nothing else changes. Line ends are kept as in the source (CRLF).
Usage (from 50_CODE/c1_av2): python -B tests/make_k8_items_v06.py
"""
import hashlib
import os

C1 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K8 = os.path.join(os.path.dirname(C1), "k8")


def rep(s, old, new):
    assert s.count(old) == 1, "expected one occurrence of %r" % old[:90]
    return s.replace(old, new)


def make(src):
    crlf = "\r\n" in src
    s = src.replace("\r\n", "\n")
    s = rep(s, '"""K8 calibration items, v05 (Claude line',
            '"""K8 calibration items, v06 (Claude line, 4 Nov 2026; generated by 50_CODE/c1_av2/tests/make_k8_items_v06.py from k8_items_v05.py,\n'
            'which is unchanged) = k8_items_v05 on c1_guard_v03 (R17c M1, m5: the latest line of the C1 hash log only, FROZEN_ENV asserted).\n'
            'K8 calibration items, v05 (Claude line')
    s = rep(s, "import c1_guard_v02 as G  # noqa: E402\n", "import c1_guard_v03 as G  # noqa: E402\n")
    s = rep(s, '    print("K8 ITEMS V05 DONE")\n', '    print("K8 ITEMS V06 DONE")\n')
    return s.replace("\n", "\r\n") if crlf else s


def main():
    with open(os.path.join(K8, "k8_items_v05.py"), encoding="utf-8", newline="") as f:
        out = make(f.read())
    with open(os.path.join(K8, "k8_items_v06.py"), "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print(hashlib.sha256(out.encode("utf-8")).hexdigest(), "k8_items_v06.py")


if __name__ == "__main__":
    main()
