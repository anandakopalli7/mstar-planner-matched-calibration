#!/usr/bin/env python3
"""Generator of 50_CODE/k8/k8_items_v07.py from k8_items_v06.py (not modified), asserted replacements (D16 v21 Choice 42; R17d B1, (g)).
v07 is v06 on c1_guard_v04: --av2-stageB needs the validated deposit record (guard, role entry:k8_items; besides the cache chain's own
check); an existing output (items, summary) is refused; the summary records deposit_record_sha256; one line is appended to
40_PROTOCOL/C1_RUN_LOG.txt. Line ends are kept as in the source (CRLF).
Usage (from 50_CODE/c1_av2): python -B tests/make_k8_items_v07.py
"""
import hashlib
import os

C1 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K8 = os.path.join(os.path.dirname(C1), "k8")


def rep(s, old, new):
    assert s.count(old) == 1, "expected one occurrence of %r" % old[:90]
    return s.replace(old, new)


def make(src):
    crlf = "\r\n" in src
    s = src.replace("\r\n", "\n")
    s = rep(s, '"""K8 calibration items, v06 (Claude line',
            '"""K8 calibration items, v07 (Claude line, 4 Nov 2026; generated by 50_CODE/c1_av2/tests/make_k8_items_v07.py from k8_items_v06.py,\n'
            'which is unchanged) = k8_items_v06 on c1_guard_v04 (D16 v21 Choice 42): --av2-stageB needs the validated deposit record; an existing\n'
            'output is refused; the summary records deposit_record_sha256; one line in 40_PROTOCOL/C1_RUN_LOG.txt.\n'
            'K8 calibration items, v06 (Claude line')
    s = rep(s, "import c1_guard_v03 as G  # noqa: E402\n", "import c1_guard_v04 as G  # noqa: E402\n")
    s = rep(s, '        plan_sha, frozen, rt = G.guard("av2", a.plan, "entry:k8_items", os.path.abspath(__file__))\n',
            '        plan_sha, frozen, rt = G.guard("av2", a.plan, "entry:k8_items", os.path.abspath(__file__))\n'
            '        G.refuse_existing([a.out, a.out.replace(".npz", "_summary.json")], "av2")\n')
    s = rep(s, '            "code": G.verify_runtime_again(frozen, rt) if rt else G.code_record(os.path.abspath(__file__))}\n',
            '            "code": G.verify_runtime_again(frozen, rt) if rt else G.code_record(os.path.abspath(__file__)),\n'
            '            "deposit_record_sha256": rt["deposit_record_sha256"] if rt else "exempt (nuscenes or stage A)"}\n')
    s = rep(s, '    print("K8 ITEMS V06 DONE")\n',
            '    if rt:\n'
            '        G.run_log_append("av2", os.path.abspath(__file__), plan_sha, rt["deposit_record_sha256"], {"manifests": man_sha},\n'
            '                         [a.out, a.out.replace(".npz", "_summary.json")])\n'
            '    print("K8 ITEMS V07 DONE")\n')
    return s.replace("\n", "\r\n") if crlf else s


def main():
    with open(os.path.join(K8, "k8_items_v06.py"), encoding="utf-8", newline="") as f:
        out = make(f.read())
    with open(os.path.join(K8, "k8_items_v07.py"), "w", encoding="utf-8", newline="") as f:
        f.write(out)
    print(hashlib.sha256(out.encode("utf-8")).hexdigest(), "k8_items_v07.py")


if __name__ == "__main__":
    main()
